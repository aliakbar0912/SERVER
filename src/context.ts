// The dependencies handed to every route. Nothing here is a global, so tests can build an app with their own database and clock.
import type { IncomingMessage, ServerResponse } from 'node:http';
import type { Config } from './config.ts';
import type { Db } from './db/pg-wire.ts';
import type { LimitStore } from './limits.ts';
import type { Redis } from './redis.ts';

export interface Deps {
  db: Db;
  config: Config;
  /** Rate limits, cache and locks: Redis when configured, otherwise PostgreSQL. */
  limits: LimitStore;
  /** The Redis client when REDIS_URL is set, for health checks. */
  redis: Redis | null;
  /** Upstream calls go through this. Tests replace it to pin timeouts or to observe requests. */
  fetch: typeof fetch;
}

export interface Ctx {
  req: IncomingMessage;
  res: ServerResponse;
  url: URL;
  params: Record<string, string>;
  ip: string;
  /** Generated by the server for every request. Returned as x-request-id and stored with usage records. */
  requestId: string;
  deps: Deps;
}

export interface OwnerSession {
  sessionId: string;
  ownerId: string;
  email: string;
  csrfToken: string;
  reauthUntil: Date | null;
  dbNow: Date;
}

export interface DeviceAuth {
  deviceId: string;
  name: string;
  /** 'all' = every enabled model; 'selected' = only the models granted to this device. */
  modelAccess: 'all' | 'selected';
}
